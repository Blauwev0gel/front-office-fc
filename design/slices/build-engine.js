// Copies the real Northmarch engine (no UI) into engine.js for the prototype slices (MB-19: prototypes run on the real engine).
// Usage: node design/slices/build-engine.js
const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'../../standalone/front-office-fc/northmarch-layered');
const {ENGINE}=require(path.join(root,'build.js'));
const js=ENGINE.map(f=>`/* ---- ${f} ---- */\n`+fs.readFileSync(path.join(root,'src',f),'utf8')).join('\n');
fs.writeFileSync(path.join(__dirname,'engine.js'),`/* Northmarch engine, generated by build-engine.js from northmarch-layered/src. Do not edit. */\n${js}\n`);
console.log('engine.js',Math.round(js.length/1024),'KB,',ENGINE.length,'modules');
